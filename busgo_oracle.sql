

CREATE TABLE bg_passengers (
    passenger_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_name VARCHAR2(100) NOT NULL,
    mobile VARCHAR2(10) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE bg_buses (
    bus_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator VARCHAR2(100) NOT NULL,
    pickup VARCHAR2(100) NOT NULL,
    drop_location VARCHAR2(100) NOT NULL,
    bus_type VARCHAR2(60) NOT NULL,
    departure VARCHAR2(25) NOT NULL,
    arrival VARCHAR2(25) NOT NULL,
    fare NUMBER(10,2) NOT NULL,
    active CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT bg_buses_active_ck CHECK (active IN ('Y','N')),
    CONSTRAINT bg_buses_fare_ck CHECK (fare >= 0)
);

CREATE TABLE bg_bookings (
    ticket_id VARCHAR2(30) PRIMARY KEY,
    passenger_id NUMBER NOT NULL REFERENCES bg_passengers(passenger_id),
    bus_id NUMBER NOT NULL REFERENCES bg_buses(bus_id),
    journey_date DATE NOT NULL,
    total_fare NUMBER(10,2) NOT NULL,
    payment_method VARCHAR2(40) NOT NULL,
    payment_status VARCHAR2(30) NOT NULL,
    booking_status VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT bg_bookings_status_ck CHECK (booking_status IN ('CONFIRMED','CANCELLED'))
);

CREATE TABLE bg_booking_seats (
    seat_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id VARCHAR2(30) NOT NULL REFERENCES bg_bookings(ticket_id),
    bus_id NUMBER NOT NULL REFERENCES bg_buses(bus_id),
    journey_date DATE NOT NULL,
    seat_no NUMBER(2) NOT NULL,
    CONSTRAINT bg_seat_no_ck CHECK (seat_no BETWEEN 1 AND 24),
    CONSTRAINT bg_unique_bus_date_seat UNIQUE (bus_id, journey_date, seat_no)
);

CREATE TABLE bg_payments (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id VARCHAR2(30) NOT NULL REFERENCES bg_bookings(ticket_id),
    payment_method VARCHAR2(40) NOT NULL,
    amount NUMBER(10,2) NOT NULL,
    payment_status VARCHAR2(30) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX bg_bookings_date_ix ON bg_bookings(journey_date);
CREATE INDEX bg_buses_route_ix ON bg_buses(pickup, drop_location);

